#!/usr/bin/env node
/**
 * ui-axes-audit — считает по коду, у каких из десяти осей интерфейса есть канон,
 * а какие разъезжаются. Работает на любом фронтенд-репозитории.
 *
 * Полный разбор осей: docs/UI_ARCHITECTURE_AXES.md.
 *
 * Осознанные границы этого инструмента:
 *   — он НЕ судит о красоте и не заменяет взгляд на экран;
 *   — он считает СЛЕДЫ решения в коде: есть ли шкала, сколько значений живёт в
 *     одной роли, есть ли канонические компоненты состояний;
 *   — «канон есть» здесь значит «в коде видно одно место, где это задано»,
 *     а не «решение правильное».
 *
 * Запуск:
 *   node ui-axes-audit.mjs --repo /путь/к/проекту [--json отчёт.json]
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const argOf = (имя, поум = null) => {
  const i = args.indexOf(имя);
  return i >= 0 && args[i + 1] ? args[i + 1] : поум;
};
const REPO = path.resolve(argOf('--repo', process.cwd()));
const JSON_OUT = argOf('--json');
// Части репозитория со своим дизайн-языком (маркетинговый сайт, лендинги)
// считать вместе с продуктом нельзя — у них другая система по построению.
const ИСКЛ_ПУТИ = (argOf('--exclude', '') || '').split(',').filter(Boolean);


const isMain = process.argv[1] === fileURLToPath(import.meta.url);

if (isMain) {
  if (!fs.existsSync(REPO)) {
    console.error(`[ui-axes] нет каталога: ${REPO}`);
    process.exit(1);
  }

  /** Ищем только исходники интерфейса, без сборок, зависимостей и тестов. */
  const ИСКЛЮЧИТЬ = [
    'node_modules', '.next', 'dist', 'build', 'coverage', '.git',
    '__tests__', '.claude',
  ];
  const ФАЙЛЫ = [];
  (function обойти(dir) {
    let список;
    try { список = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const d of список) {
      if (ИСКЛЮЧИТЬ.includes(d.name)) continue;
      const p = path.join(dir, d.name);
      if (d.isDirectory()) обойти(p);
      else if (
        /\.(tsx|jsx)$/.test(d.name) &&
        !/\.(test|spec)\./.test(d.name) &&
        !ИСКЛ_ПУТИ.some((x) => p.includes(x))
      ) ФАЙЛЫ.push(p);
    }
  })(REPO);

  const ТЕКСТ = ФАЙЛЫ.map((f) => {
    try { return fs.readFileSync(f, 'utf8'); } catch { return ''; }
  }).join('\n');

  const счёт = (re) => (ТЕКСТ.match(re) || []).length;
  const гисто = (re, верх = 8) => {
    const m = ТЕКСТ.match(re) || [];
    const счётчик = new Map();
    for (const x of m) счётчик.set(x, (счётчик.get(x) || 0) + 1);
    return [...счётчик.entries()].sort((a, b) => b[1] - a[1]).slice(0, верх);
  };
  const естьФайл = (...кандидаты) =>
    кандидаты.some((c) => fs.existsSync(path.join(REPO, c)));
  const вКонфиге = (ключ) => {
    for (const c of ['tailwind.config.ts', 'tailwind.config.js']) {
      const p = path.join(REPO, c);
      if (!fs.existsSync(p)) continue;
      if (new RegExp(`\\b${ключ}\\s*:\\s*\\{`).test(fs.readFileSync(p, 'utf8'))) return true;
    }
    return false;
  };
  const вСтилях = (re) => {
    for (const c of ['app/globals.css', 'src/globals.css', 'styles/globals.css', 'src/index.css']) {
      const p = path.join(REPO, c);
      if (!fs.existsSync(p)) continue;
      if (re.test(fs.readFileSync(p, 'utf8'))) return true;
    }
    return false;
  };

  const оси = [];

  // ── 1. Цвет ────────────────────────────────────────────────────────────────
  {
    const токены = вСтилях(/--(text|surface|border)-[a-z]/);
    const сырые = счёт(/text-(emerald|green|blue|sky|cyan|amber|yellow|orange|red|rose|violet|purple|indigo|pink|teal)-(200|300|400)\b/g);
    оси.push({
      ось: 'цвет',
      канон: токены,
      разъезд: сырые,
      заметка: токены
        ? `семантические переменные есть; чернил из сырой палитры: ${сырые}`
        : 'семантических переменных не найдено — цвет решается на каждом экране',
    });
  }

  // ── 2. Ритм ────────────────────────────────────────────────────────────────
  {
    // Волоски (gap-0.5 = 2px и подобные) — отдельная роль, а не конкурент
    // основному зазору: считать их разъездом значит наказывать за правильное.
    const g = гисто(/\bgap-[0-9.]+/g).filter(([k]) => {
      const v = parseFloat(k.replace('gap-', ''));
      return !Number.isNaN(v) && v >= 1;
    });
    const именованные = счёт(/\bgap-(?:hair|icon|tight|base|inset|card|roomy|section|page)\b/g);
    const ролей = g.filter(([, n]) => n > Math.max(20, (g[0]?.[1] || 0) * 0.15)).length;
    оси.push({
      ось: 'ритм (отступы)',
      канон: вКонфиге('spacing') && именованные > 0,
      разъезд: ролей > 3 ? ролей : 0,
      заметка: `именованных шагов ${именованные}; числовых значений с заметной долей: ${ролей}` +
        (g.length ? ` — ${g.slice(0, 5).map(([k, n]) => `${k}×${n}`).join(', ')}` : ''),
    });
  }

  // ── 3. Радиусы ─────────────────────────────────────────────────────────────
  {
    const именами = счёт(/rounded-(element|inner|card|container|pill)\b/g);
    const мимо = счёт(/rounded-(md|lg|xl|2xl|3xl|full)\b/g);
    const числом = счёт(/rounded-\[[0-9]+px\]/g);
    оси.push({
      ось: 'радиусы',
      канон: вКонфиге('borderRadius') && именами > мимо,
      разъезд: мимо + числом,
      заметка: `по шкале ${именами}, мимо шкалы ${мимо}, числом ${числом}`,
    });
  }

  // ── 4. Типографика ─────────────────────────────────────────────────────────
  {
    const межстрочный = вСтилях(/--lh-|line-height/);
    оси.push({
      ось: 'типографика',
      канон: вКонфиге('fontSize'),
      разъезд: межстрочный ? 0 : 1,
      заметка: вКонфиге('fontSize')
        ? (межстрочный ? 'шкала кегля и межстрочный заданы' : 'шкала кегля есть, межстрочный интерфейсного текста не задан')
        : 'шкалы кегля нет',
    });
  }

  // ── 5. Состояния поверхности ───────────────────────────────────────────────
  {
    const пусто = ФАЙЛЫ.filter((f) => /EmptyState|Nothing |No .{2,20} yet/.test(fs.readFileSync(f, 'utf8'))).length;
    const грузится = ФАЙЛЫ.filter((f) => /Skeleton|animate-pulse/.test(fs.readFileSync(f, 'utf8'))).length;
    const ошибка = ФАЙЛЫ.filter((f) => /ErrorState|Couldn.t load|Try again|Retry/.test(fs.readFileSync(f, 'utf8'))).length;
    оси.push({
      ось: 'состояния поверхности',
      канон: естьФайл('components/ui/ErrorState.tsx', 'components/ui/EmptyState.tsx'),
      разъезд: пусто > 0 && ошибка < пусто / 3 ? пусто - ошибка : 0,
      заметка: `пусто в ${пусто} файлах, скелетон в ${грузится}, ошибка в ${ошибка}` +
        (ошибка < пусто / 3 ? ' — при сбое человек видит пустоту и не понимает, сломалось или нет данных' : ''),
    });
  }

  // ── 6. Плотность ───────────────────────────────────────────────────────────
  {
    const есть = вСтилях(/--density|--row-h/) || счёт(/data-density|useDensity/g) > 0;
    оси.push({
      ось: 'плотность',
      канон: есть,
      разъезд: есть ? 0 : 1,
      заметка: есть ? 'решение о плотности зафиксировано' : 'решения нет — каждая таблица выбирает высоту строки сама',
    });
  }

  // ── 7. Движение ────────────────────────────────────────────────────────────
  {
    const токены = вСтилях(/--duration|--ease|--motion/);
    const руками = счёт(/duration-\[[0-9]+ms\]|transition-duration:\s*[0-9]/g);
    оси.push({
      ось: 'движение',
      канон: токены,
      разъезд: руками,
      заметка: `${токены ? 'токены длительности есть' : 'токенов длительности нет'}; длительностей руками: ${руками}`,
    });
  }

  // ── 8. Последствия ─────────────────────────────────────────────────────────
  {
    // Считаем ИСПОЛЬЗОВАНИЯ в разметке, а не упоминания: прежняя версия ловила
    // импорты, комментарии и типы и завышала счёт втрое (замер projectx-app:
    // «175» против 67 реальных мест).
    // Отмену ищем и через канонический помощник: undoable() сам ставит кнопку,
    // поэтому строки "Undo" в компоненте больше нет — считать только её значит
    // не увидеть правильное применение.
    const отмена =
      счёт(/label:\s*["']Undo["']|>\s*Undo\s*<|onUndo[=(]/g) + счёт(/\bundoable\(/g);
    const подтверждение = счёт(/<ConfirmDialog/g);
    const нативные = счёт(/window\.confirm\(/g);
    // Само по себе число подтверждений НЕ дефект: в projectx-app все 63 стояли
    // на необратимом (удалить, отозвать ключ, отключить интеграцию) — и это
    // правильно. Дефект — вешать подтверждение на ОБРАТИМОЕ действие, а этого
    // машина не различает. Поэтому здесь нет приговора: инструмент сообщает
    // соотношение и напоминает, что именно надо проверить глазами.
    const перекос = отмена === 0 && подтверждение > 0;
    оси.push({
      ось: 'последствия (отмена/подтверждение)',
      канон: отмена > 0 && подтверждение > 0 && !перекос,
      разъезд: перекос ? подтверждение : 0,
      заметка: `отмена в ${отмена} местах, подтверждение в ${подтверждение}` +
        (нативные ? `, нативных window.confirm ${нативные} — их видно только в браузерном окне и стилизовать нельзя` : '') +
        (отмена === 0
          ? ' — отмены нет вовсе, средняя корзина оси пуста'
          : подтверждение > отмена * 5
            ? ' — проверь глазами: подтверждение законно только на необратимом, у обратимого должна быть отмена'
            : ''),
    });
  }

  // ── 9. Границы содержимого ─────────────────────────────────────────────────
  {
    const обрезка = счёт(/\btruncate\b|line-clamp-/g);
    const цифры = счёт(/tabular-nums/g);
    const форматтеры = естьФайл('lib/formatters', 'src/lib/formatters', 'lib/format');
    оси.push({
      ось: 'границы содержимого',
      канон: форматтеры && обрезка > 0,
      разъезд: цифры === 0 ? 1 : 0,
      заметка: `обрезка в ${обрезка} местах, выравнивание цифр в ${цифры}, ` +
        (форматтеры ? 'форматтеры вынесены' : 'общих форматтеров нет'),
    });
  }

  // ── 10. Клавиатура и фокус ─────────────────────────────────────────────────
  {
    const кольцо = счёт(/FOCUS_RING|focus-visible:ring/g);
    const хоткеи = естьФайл('lib/hotkeys', 'src/lib/hotkeys') || счёт(/useHotkey|hotkeyRegistry/g) > 0;
    оси.push({
      ось: 'клавиатура и фокус',
      канон: кольцо > 0 && хоткеи,
      разъезд: кольцо === 0 ? 1 : 0,
      заметка: `видимый фокус в ${кольцо} местах, ${хоткеи ? 'реестр горячих клавиш есть' : 'реестра горячих клавиш нет'}`,
    });
  }

  // ── вывод ──────────────────────────────────────────────────────────────────
  const шир = Math.max(...оси.map((o) => o.ось.length));
  console.log(`\nДесять осей интерфейса — ${path.basename(REPO)} (${ФАЙЛЫ.length} файлов)\n`);
  for (const o of оси) {
    const знак = o.канон && !o.разъезд ? '✓' : o.канон ? '~' : '✗';
    console.log(`${знак} ${o.ось.padEnd(шир)}  ${o.заметка}`);
  }
  const без = оси.filter((o) => !o.канон).length;
  const шатко = оси.filter((o) => o.канон && o.разъезд).length;
  console.log(`\nбез канона: ${без}, с каноном но разъезжаются: ${шатко}, закрыто: ${оси.length - без - шатко}`);
  console.log('разбор осей: ~/.claude/jidoka/docs/UI_ARCHITECTURE_AXES.md\n');

  if (JSON_OUT) {
    fs.writeFileSync(JSON_OUT, JSON.stringify({ repo: REPO, файлов: ФАЙЛЫ.length, оси }, null, 1));
    console.log(`отчёт: ${JSON_OUT}`);
  }
  process.exit(0);
}
