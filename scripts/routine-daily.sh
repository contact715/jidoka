#!/usr/bin/env bash
# Ежедневная рутина — самая частая каденция.
#
# Ловит дрейф, который недельная проверка заметит на шесть дней позже. Правило
# отбора сюда жёсткое: проверка попадает в ежедневную рутину, только если она
# (а) укладывается в считанные секунды, (б) не дёргает агентов и не тратит
# токены, (в) её результат может измениться за сутки. Всё остальное живёт в
# недельной или месячной рутине.
#
# Отчёт НЕ пишется файлом намеренно: 365 файлов в год никто не читает, а дифф
# день-к-дню бесполезен. Вывод идёт в stdout, его забирает утренний дайджест
# (~/.claude/hooks/daily-digest.sh) и кладёт в отчёт за день.
#
# Запуск:
#   npm run routine:daily
#   bash scripts/routine-daily.sh
#
# Расписание: отдельный будильник не нужен, ежедневный дайджест уже просыпается
# в 09:00 через launchd-агент com.mityamit.claude-daily-digest и зовёт эту рутину.
# Подробнее: docs/ROUTINES.md.

set -uo pipefail

# Считаем корень от СВОЕГО файла, а не от текущей папки. Рутину зовёт launchd
# из произвольного места, а `git rev-parse` в такой ситуации уводит в чужой
# репозиторий, где скриптов нет, и рутина молча рапортует «пропускаем».
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"
cd "$ROOT" || exit 0

echo "Ежедневная рутина — $(date '+%d.%m.%Y %H:%M')"
echo ""

# 1. Свежесть официальных скиллов и плагинов Anthropic.
#    Меняется в любой день без предупреждения: Anthropic пушит в свой репозиторий,
#    у нас продолжает лежать старая копия и никто об этом не узнаёт.
echo "1. Свежесть официальных скиллов"
if [ -f scripts/skills-freshness.mjs ]; then
  node scripts/skills-freshness.mjs 2>&1 || echo "   (проверка не отработала, пропускаем)"
else
  echo "   (scripts/skills-freshness.mjs не найден, пропускаем)"
fi

echo ""

# 2. Незакрытые ЧЕЛОВЕЧЕСКИЕ шаги — очередь с возрастом.
#    Механизм строится, доказывается и упирается в шаг, который может сделать только
#    человек (вставка в L0-реестр, решение по лицензии, одобрение расхода). У такого шага
#    не было ни очереди, ни возраста, ни счётчика: он жил в выводе одной команды, которую
#    надо было не забыть запустить. Замер 2026-08-17: готовый блок регистрации семи гейтов
#    печатался семь дней подряд и не был вставлен ни разу.
#    Сначала обновляем очередь из обратной оси реестра гейтов, потом печатаем её.
echo "2. Шаги, которые ждут человека"
if [ -f scripts/pending-human.mjs ]; then
  node scripts/gate-audit.mjs --emit-pending >/dev/null 2>&1 || true
  node scripts/pending-human.mjs 2>&1 || echo "   (очередь не прочиталась, пропускаем)"
else
  echo "   (scripts/pending-human.mjs не найден, пропускаем)"
fi

echo ""

# 3. Расхождение канона и УСТАНОВЛЕННОЙ копии (2026-W35-A5).
#    Сессии работают не в этом репозитории, а в ~/.claude/jidoka. Прибор сравнения был
#    построен ещё в W33, работает и краснеет — и его никто не звал: ни git-хук, ни CI, ни
#    npm. Замер 2026-08-24: копия отставала на 11 скриптов, среди них gate-honesty-check и
#    suppression-not-a-fix, то есть механизмы, которые реестр называет средствами закрытых
#    классов. Класс считался закрытым механизмом, которого в рабочем месте нет.
#    Рутина печатает вердикт, но НЕ падает: расхождение чинится синхронизацией, а не
#    остановкой дня. Копии нет вовсе — честное «сравнивать не с чем» и тишина.
#    Сравнение обязано идти ИЗ КАНОНА: рутину зовёт launchd из установленной копии, а
#    сравнение копии с самой собой даёт бессмысленное «совпадают». Поэтому ищем клон
#    канона: сначала переменная окружения (переносимо), потом привычное место. Не нашли —
#    говорим об этом прямо, а не печатаем зелёное.
echo "3. Канон против установленной копии"
CANON=""
for c in "${JIDOKA_CANON:-}" "$HOME/jidoka-framework" "$HOME/.jidoka-weekly"; do
  if [ -n "$c" ] && [ -f "$c/scripts/install-into.mjs" ] && [ "$c" != "$ROOT" ]; then CANON="$c"; break; fi
done
if [ -n "$CANON" ]; then
  echo "   канон: $CANON"
  (cd "$CANON" && node scripts/install-into.mjs --check-parity 2>&1) || true
elif [ -f scripts/install-into.mjs ]; then
  node scripts/install-into.mjs --check-parity 2>&1 || true
else
  echo "   (scripts/install-into.mjs не найден, пропускаем)"
fi

# 4. Достижимость git-хуков из КАЖДОЙ рабочей копии (2026-W35-A4).
#    core.hooksPath живёт в общем .git/config, поэтому настройка выглядит сделанной из любой
#    копии, а срабатывает не везде. Измерено экспериментом 2026-08-24: копия на ветке без
#    каталога .githooks коммитит вообще без хуков и без предупреждения. Отсюда инцидент
#    2026-08-23 «4 дерева из 6 пушили без гейта». Рутина печатает, но НЕ падает: чинится
#    это веткой и конфигом, а не остановкой дня.
echo ""
echo "4. Достижимость git-хуков по рабочим копиям"
if [ -f scripts/hooks-reachability.mjs ]; then
  node scripts/hooks-reachability.mjs 2>&1 || true
else
  echo "   (scripts/hooks-reachability.mjs не найден, пропускаем)"
fi

# --- состояние машины (2026-08-22) ---
# Владелец перезагружал компьютер пять раз за сутки: Claude уходил в 50 ГБ при 18 ГБ
# физической памяти, и ни один сторож этого не видел — очередь тяжёлых задач привязана
# к каталогу, а рабочих копий несколько. Рутина печатает вердикт, но НЕ падает: она не
# должна блокировать день из-за того, что в этот момент идёт чья-то сборка.
if [ -f scripts/machine-guard.mjs ]; then
  echo ""
  node scripts/machine-guard.mjs --check || true
fi

# --- доска параллельных сессий (2026-08-22) ---
# Роль тимлида начинается с фактов: кто ещё работает и не столкнёмся ли мы. Рутина печатает
# пересечения, но НЕ падает: доска советует, решение за человеком.
if [ -f scripts/session-board.mjs ]; then
  echo ""
  node scripts/teamlead.mjs || true
fi

# --- брошенные процессы (2026-08-24) ---
# Два процесса, оставленные умершей 22 августа сессией, прожили 46 часов и вдвоём жгли
# около 1,75 ядра непрерывно. Машина ушла в подкачку: своп 12,9 из 14,3 ГБ, свободной
# памяти 0,1 ГБ, средняя загрузка 49 при 12 ядрах. Нашёл их не прибор, а владелец —
# по тормозам.
#
# Печатаем, но НИЧЕГО не трогаем: снятие процесса это решение человека, а рутина ходит
# по расписанию в 09:00, когда за машиной может никого не быть. --all, чтобы видеть
# брошенное во ВСЕХ проектах: чужой холостой цикл ест ту же память, что и свой.
if [ -f scripts/process-health.mjs ]; then
  echo ""
  echo "5. Брошенные процессы (снятие — решение человека)"
  node scripts/process-health.mjs --all || true
fi

# 2026-W35: выход перенесён СЮДА из середины файла. Он стоял сразу после раздела 2, поэтому
# оба блока выше — состояние машины и доска параллельных сессий, оба написаны 2026-08-22 —
# не выполнялись ни разу. Механизм, дописанный ПОСЛЕ выхода, выглядит подключённым и не
# работает; ровно этот класс рутина теперь и проверяет разделом 3.
echo ""
exit 0
