#!/usr/bin/env bash
# Ежедневная рутина — самая частая каденция.
#
# Ловит дрейф, который недельная проверка заметит на шесть дней позже. Правило
# отбора сюда жёсткое: проверка попадает в ежедневную рутину, только если она
# (а) укладывается в считанные секунды, (б) не дёргает агентов и не тратит
# токены, (в) её результат может измениться за сутки. Всё остальное живёт в
# недельной или месячной рутине.
#
# Отчёт НЕ пишется файлом намеренно: 365 файлов в год никто не читает, а дифф
# день-к-дню бесполезен. Вывод идёт в stdout, его забирает утренний дайджест
# (~/.claude/hooks/daily-digest.sh) и кладёт в отчёт за день.
#
# Запуск:
#   npm run routine:daily
#   bash scripts/routine-daily.sh
#
# Расписание: отдельный будильник не нужен, ежедневный дайджест уже просыпается
# в 09:00 через launchd-агент com.mityamit.claude-daily-digest и зовёт эту рутину.
# Подробнее: docs/ROUTINES.md.

set -uo pipefail

# Считаем корень от СВОЕГО файла, а не от текущей папки. Рутину зовёт launchd
# из произвольного места, а `git rev-parse` в такой ситуации уводит в чужой
# репозиторий, где скриптов нет, и рутина молча рапортует «пропускаем».
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"
cd "$ROOT" || exit 0

echo "Ежедневная рутина — $(date '+%d.%m.%Y %H:%M')"
echo ""

# 1. Свежесть официальных скиллов и плагинов Anthropic.
#    Меняется в любой день без предупреждения: Anthropic пушит в свой репозиторий,
#    у нас продолжает лежать старая копия и никто об этом не узнаёт.
echo "1. Свежесть официальных скиллов"
if [ -f scripts/skills-freshness.mjs ]; then
  node scripts/skills-freshness.mjs 2>&1 || echo "   (проверка не отработала, пропускаем)"
else
  echo "   (scripts/skills-freshness.mjs не найден, пропускаем)"
fi

echo ""

# 2. Незакрытые ЧЕЛОВЕЧЕСКИЕ шаги — очередь с возрастом.
#    Механизм строится, доказывается и упирается в шаг, который может сделать только
#    человек (вставка в L0-реестр, решение по лицензии, одобрение расхода). У такого шага
#    не было ни очереди, ни возраста, ни счётчика: он жил в выводе одной команды, которую
#    надо было не забыть запустить. Замер 2026-08-17: готовый блок регистрации семи гейтов
#    печатался семь дней подряд и не был вставлен ни разу.
#    Сначала обновляем очередь из обратной оси реестра гейтов, потом печатаем её.
echo "2. Шаги, которые ждут человека"
if [ -f scripts/pending-human.mjs ]; then
  node scripts/gate-audit.mjs --emit-pending >/dev/null 2>&1 || true
  node scripts/pending-human.mjs 2>&1 || echo "   (очередь не прочиталась, пропускаем)"
else
  echo "   (scripts/pending-human.mjs не найден, пропускаем)"
fi

echo ""
exit 0

# --- состояние машины (2026-08-22) ---
# Владелец перезагружал компьютер пять раз за сутки: Claude уходил в 50 ГБ при 18 ГБ
# физической памяти, и ни один сторож этого не видел — очередь тяжёлых задач привязана
# к каталогу, а рабочих копий несколько. Рутина печатает вердикт, но НЕ падает: она не
# должна блокировать день из-за того, что в этот момент идёт чья-то сборка.
if [ -f scripts/machine-guard.mjs ]; then
  echo ""
  node scripts/machine-guard.mjs --check || true
fi
