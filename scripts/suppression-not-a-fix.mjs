#!/usr/bin/env node
// @ts-check
/**
 * Подавление — это не починка.
 *
 * @closes-class declaration-over-implementation
 *
 * ПОЧЕМУ ПОЯВИЛСЯ. hooks/proof-of-work-gate.mjs стоит с 2026-06-06 и всё равно
 * пропустил класс дважды. Он спрашивает «выполнялось ли хоть что-нибудь после
 * правки кода» — и в обоих случаях выполнялось:
 *
 *   · 2026-06-07 — «починка» объявлена после ОДНОЙ чистой проверки, до того как
 *     перерисовка вернула ту же ошибку;
 *   · 2026-06-10 — раунд фиксов отчитался «сделано», а починкой был
 *     МАСКИРУЮЩИЙ тип-каст: типы честно позеленели, потому что ошибку заткнули.
 *
 * То есть проверка проходила, но проверяла не заявленное. Отсюда другой признак,
 * дешёвый и точный: в правку ДОБАВЛЕНО подавление. `as any`, `@ts-ignore`,
 * `eslint-disable`, пропуск теста — всё это делает последующее «зелено»
 * бессмысленным. Гейт по плотности (scripts/type-coverage.mjs) такое не ловит:
 * он меряет ЗАПАС по всей базе, а один каст в большом проекте бюджет не пробьёт.
 * Здесь меряется ПОТОК — что именно добавила эта правка.
 *
 * ЧЕСТНАЯ ГРАНИЦА. Подавление иногда законно: чужой тип соврал, тест ждёт
 * бэкенда, правило линтера не про этот случай. Поэтому гейт не запрещает, а
 * требует ОБЪЯСНЕНИЕ рядом — комментарий на той же или предыдущей добавленной
 * строке, не короче 25 символов. Молчаливое подавление блокируется, объяснённое
 * проходит. Цена честности — одна строка текста.
 */

import { execSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Что считаем подавлением. */
const ПОДАВЛЕНИЯ = [
  { шаблон: /\bas\s+any\b/, имя: 'as any' },
  { шаблон: /@ts-ignore/, имя: '@ts-ignore' },
  { шаблон: /@ts-nocheck/, имя: '@ts-nocheck' },
  { шаблон: /@ts-expect-error/, имя: '@ts-expect-error' },
  { шаблон: /eslint-disable(?!-next-line\s+\S+\s+--)/, имя: 'eslint-disable' },
  { шаблон: /\b(it|test|describe)\.skip\s*\(/, имя: 'пропуск теста' },
  { шаблон: /\bx(it|describe)\s*\(/, имя: 'пропуск теста' },
];

/** Комментарий с объяснением: не короче 25 символов содержательного текста. */
const ЗНАЧИМЫЙ_КОММЕНТАРИЙ = /(?:\/\/|\/\*|\*|#)\s*(.{25,})/;

/**
 * Разбирает добавленные строки диффа по файлам.
 * @param {string} diff
 * @returns {{file: string, line: number, text: string}[]}
 */
export function добавленныеСтроки(diff) {
  const итог = [];
  let файл = '';
  let номер = 0;
  for (const строка of diff.split('\n')) {
    const m = /^\+\+\+ b\/(.+)$/.exec(строка);
    if (m) { файл = m[1]; continue; }
    const h = /^@@ -\d+(?:,\d+)? \+(\d+)/.exec(строка);
    if (h) { номер = Number(h[1]); continue; }
    if (строка.startsWith('+') && !строка.startsWith('+++')) {
      итог.push({ file: файл, line: номер, text: строка.slice(1) });
      номер++;
    } else if (!строка.startsWith('-')) {
      номер++;
    }
  }
  return итог;
}

/**
 * Ищет добавленные подавления без объяснения.
 * @param {{file: string, line: number, text: string}[]} строки
 * @returns {string[]} претензии
 */
export function молчаливыеПодавления(строки) {
  const претензии = [];
  строки.forEach((с, i) => {
    const найдено = ПОДАВЛЕНИЯ.find((п) => п.шаблон.test(с.text));
    if (!найдено) return;

    const своя = ЗНАЧИМЫЙ_КОММЕНТАРИЙ.test(с.text);
    const предыдущая = строки[i - 1];
    const рядом =
      предыдущая && предыдущая.file === с.file && предыдущая.line === с.line - 1
        ? ЗНАЧИМЫЙ_КОММЕНТАРИЙ.test(предыдущая.text)
        : false;

    if (!своя && !рядом) {
      претензии.push(
        `${с.file}:${с.line}: добавлено «${найдено.имя}» без объяснения — ${с.text.trim().slice(0, 60)}`,
      );
    }
  });
  return претензии;
}

function самопроверка() {
  const разбор = (d) => молчаливыеПодавления(добавленныеСтроки(d));
  const шапка = '+++ b/a.ts\n@@ -1,0 +1,3 @@\n';
  const случаи = [
    ['молчаливый as any ловится', разбор(шапка + '+const x = y as any;').length === 1],
    ['объяснённый на той же строке проходит',
      разбор(шапка + '+const x = y as any; // тип из чужой библиотеки врёт, см. issue 42').length === 0],
    ['объяснённый строкой выше проходит',
      разбор(шапка + '+// тип из чужой библиотеки врёт, заменить после обновления\n+const x = y as any;').length === 0],
    ['короткая отписка не считается объяснением',
      разбор(шапка + '+const x = y as any; // fix').length === 1],
    ['@ts-ignore ловится', разбор(шапка + '+// @ts-ignore').length === 1],
    ['пропуск теста ловится', разбор(шапка + '+it.skip("что-то", () => {});').length === 1],
    ['обычный код не трогается', разбор(шапка + '+const x = y as string;').length === 0],
    ['удалённая строка не считается', разбор(шапка + '-const x = y as any;').length === 0],
  ];
  let плохо = 0;
  for (const [имя, ок] of случаи) {
    process.stdout.write(`${ок ? '  ok  ' : '  FAIL'} ${имя}\n`);
    if (!ок) плохо++;
  }
  process.stdout.write(`[suppression] самопроверка: ${случаи.length - плохо}/${случаи.length}\n`);
  return плохо === 0;
}

const запущенНапрямую =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (запущенНапрямую) {
  if (process.argv.includes('--self-test')) process.exit(самопроверка() ? 0 : 1);

  let diff = '';
  try {
    diff = execSync('git diff --cached --unified=0', { encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 });
  } catch {
    process.exit(0); // не репозиторий или нет индекса — не наше дело (fail-open)
  }

  const претензии = молчаливыеПодавления(добавленныеСтроки(diff));
  if (претензии.length === 0) {
    process.stdout.write('[suppression] ✓ молчаливых подавлений не добавлено\n');
    process.exit(0);
  }

  process.stderr.write('[suppression] ПОДАВЛЕНИЕ — ЭТО НЕ ПОЧИНКА:\n');
  for (const п of претензии) process.stderr.write(`  • ${п}\n`);
  process.stderr.write(
    '\nПосле такой правки «типы зелёные» и «тесты прошли» больше ничего не доказывают:\n' +
    'ошибку не убрали, а заткнули. Класс declaration-over-implementation, повтор\n' +
    '2026-06-10 — раунд фиксов отчитался «сделано», починкой был маскирующий каст.\n' +
    '\nЕсли подавление ЗАКОННО (чужой тип врёт, тест ждёт бэкенда) — объясни это\n' +
    'комментарием рядом, от 25 символов. Гейт не запрещает, он требует причину.\n',
  );
  process.exit(1);
}
