#!/usr/bin/env node
/**
 * process-health — зависшие процессы рабочей машины: найти, назвать, убрать.
 *
 * ЗАЧЕМ. Автономный прогон оставляет за собой хвосты: сессия умирает, а
 * запущенный ею скрипт продолжает висеть. Он не ест процессор и не мешает
 * заметно, поэтому живёт сутками и обнаруживается случайно. Замер
 * 2026-08-15 (projectx-app): фаззер `run-fuzz.mjs` висел 5 часов 24 минуты
 * при собственном потолке выполнения в 200 секунд. Его дескрипторы вывода
 * указывали в никуда — сессия, которая его запустила, умерла, и он ждал
 * события, которое уже не наступит.
 *
 * ГЛАВНОЕ ПРАВИЛО БЕЗОПАСНОСТИ — и оно тут не формальность. Рядом с этим
 * фаззером висели два процесса MCP по 18 часов, и по внешнему виду они
 * ничем не отличались: тот же node, тот же ноль процессора, та же вечность
 * в списке. Разница в одном поле — их РОДИТЕЛЬ ЖИВ, это работающие сессии
 * Claude. Убить такой процесс значит сломать чужую живую работу.
 *
 * Поэтому инструмент трогает только сирот: родитель равен 1 (launchd/init),
 * то есть тот, кто запускал, уже мёртв. Всё остальное он называет, но не
 * трогает — «долго» это не «зависло».
 *
 * ЧТО СЧИТАЕТСЯ ЗАВИСШИМ. Признаки работают ВМЕСТЕ, поодиночке каждый врёт:
 *   1. сирота       — родитель 1, ИЛИ корень рода осиротел (см. ниже);
 *   2. наш          — команда указывает на скрипт проекта или на известный
 *                     инструмент прогона (node/python из репозитория);
 *   3. без движения — процессор около нуля дольше порога,
 *      ЛИБО
 *   3'. вывод мёртв — все три дескриптора указывают в никуда.
 *
 * Одного признака мало: демон бывает сиротой законно, а долгая сборка
 * законно ест ноль процессора, ожидая ввода-вывода.
 *
 * СИРОТСТВО СЧИТАЕТСЯ ПО РОДУ, А НЕ ПО СВОЕМУ ppid. Найдено 2026-08-24:
 * машина ушла в подкачку, виновником был сервер разработки, проживший
 * 46 часов и жёгший целое ядро. Прибор его не увидел, и вот почему:
 *
 *   89665  next dev -p 3009   ppid=1 — СИРОТА, но процессор низкий:
 *                             это лишь запускатель
 *   89670  next-server        ppid=89665 — жжёт 100%, но по своему ppid
 *                             НЕ сирота
 *
 * Ни один не проходил оба условия: сирота не жгла, жгущий не был сиротой.
 * Двухуровневый запускатель разводит признаки по разным процессам, и
 * проверка «ppid === 1» у самого процесса промахивается по построению.
 * Теперь род прослеживается вверх до предка с ppid === 1, и приговор
 * выносится по НЕМУ.
 *
 * Но «род кончается на единице» само по себе не значит ничего: у ЛЮБОГО
 * процесса род кончается на launchd. Значение имеет, ЧЕМ является корень
 * рода. Приложение (Claude.app, браузер) или служба системы — это законный
 * корень, там ppid === 1 по построению. А вот `node`, `python`, `npm`,
 * запущенные когда-то из сессии и оказавшиеся с родителем 1, — это остаток
 * умершей сессии, и весь их подрод брошен вместе с ними.
 *
 * ТРЕТИЙ ПРИЗНАК: МЁРТВЫЙ ВЫВОД. Он и разрешает трогать КРУТЯЩИЙСЯ процесс,
 * чего прибор раньше не делал никогда. Если все три дескриптора (ввод,
 * вывод, ошибки) указывают в `->(none)`, то читать вывод некому: та сторона
 * канала закрыта вместе с сессией. Процесс может жечь ядро сколько угодно,
 * результат его работы не увидит никто. Это заключение, а не догадка, и оно
 * НЕ зависит от процента процессора — именно поэтому оно закрывает щель,
 * в которую провалились оба виновника 24 августа.
 *
 * Проверка стоит один вызов lsof на процесс, поэтому делается ТОЛЬКО для
 * кандидатов (сирота по роду плюс возраст выше порога), а не для всех
 * пятисот процессов машины.
 *
 * Использование:
 *   node process-health.mjs                     — только показать
 *   node process-health.mjs --fix               — убрать сирот (сначала TERM, потом KILL)
 *   node process-health.mjs --root <путь>       — что считать «нашим» (умолчание: текущая папка)
 *   node process-health.mjs --all               — брошенное в чужих проектах тоже можно трогать
 *   node process-health.mjs --minutes 30        — порог возраста, минут (умолчание 30)
 *   node process-health.mjs --json
 *   node process-health.mjs --self-test
 */

import { execFileSync } from "node:child_process";
import { fileURLToPath } from 'node:url';

const ПОРОГ_МИНУТ_ПО_УМОЛЧАНИЮ = 30;
const ПОРОГ_ПРОЦЕССОРА = 1.0; // %
/** Дольше этого «работает» перестаёт быть объяснением. Сутки. */
const ДОЛГО_МИНУТ = 24 * 60;

/**
 * Службы операционной системы. Они СИРОТЫ ПО ПОСТРОЕНИЮ (их растит launchd)
 * и заняты по построению же: отрисовка экрана, звук, индексация.
 *
 * Первая версия проверки холостых циклов записала в подозреваемые
 * `WindowServer` — он жёг 50% процессора 514 часов подряд. Формально всё
 * сходилось: сирота, считает, давно. По сути это macOS, который рисует
 * экран, и трогать его нельзя даже мысленно. Сторож, который ругается на
 * операционную систему, быстро перестают читать целиком — а вместе с шумом
 * теряются и настоящие находки.
 */
const СИСТЕМНЫЕ = [
    "/System/",
    "/usr/libexec/",
    "/usr/sbin/",
    "/sbin/",
    "/Library/Apple/",
    "/Applications/Safari.app/Contents/",
];

/** `ps` отдаёт возраст как [[дни-]часы:]минуты:секунды. Переводим в минуты. */
export function возрастВМинутах(строка) {
    if (!строка || typeof строка !== "string") return 0;
    const s = строка.trim();
    let дни = 0;
    let остаток = s;
    const дефис = s.indexOf("-");
    if (дефис > 0) {
        дни = Number(s.slice(0, дефис)) || 0;
        остаток = s.slice(дефис + 1);
    }
    const части = остаток.split(":").map((ч) => Number(ч) || 0);
    let часы = 0;
    let минуты = 0;
    let секунды = 0;
    if (части.length === 3) [часы, минуты, секунды] = части;
    else if (части.length === 2) [минуты, секунды] = части;
    else [секунды] = части;
    return дни * 1440 + часы * 60 + минуты + секунды / 60;
}

/**
 * Корень рода: поднимаемся по родителям до того, у кого ppid === 1.
 * Возвращает этот процесс, либо null, если цепочка оборвалась (процесс уже
 * умер) или закольцевалась.
 *
 * Чистая функция: принимает карту pid → процесс, в систему не ходит.
 */
export function корневойПредок(процесс, поPid) {
    let текущий = процесс;
    const виденные = new Set();
    while (текущий && текущий.ppid !== 1) {
        if (виденные.has(текущий.pid)) return null; // кольцо, такого быть не должно
        виденные.add(текущий.pid);
        const родитель = поPid.get(текущий.ppid);
        if (!родитель) return null; // родитель уже умер, род не проследить
        текущий = родитель;
    }
    return текущий ?? null;
}

/**
 * Брошен ли корень рода. У ЛЮБОГО процесса род кончается на launchd, поэтому
 * сам факт ppid === 1 не значит ничего. Значение имеет, чем корень является.
 *
 * Законный корень: служба системы или приложение — у них ppid === 1 по
 * построению, их растит launchd.
 *
 * Брошенный корень: инструмент, который запускают из сессии (node, python,
 * npm, npx, bun, deno, ruby, uvicorn). Если такой оказался с родителем 1,
 * значит запустившая его сессия умерла, и весь подрод остался без хозяина.
 */
export function кореньБрошен(корневой) {
    if (!корневой) return false;
    const к = корневой.команда;
    if (СИСТЕМНЫЕ.some((путь) => к.startsWith(путь))) return false;

    // Приложением считаем не всякий .app, а только тот, что лежит в папке
    // приложений. Первая версия отсекала любой путь с `.app/Contents/MacOS/`
    // — и на самопроверке выяснилось, что она исключает питон от Homebrew:
    // он ставится как /opt/homebrew/Cellar/python@3.13/.../Python.framework/
    // .../Python.app/Contents/MacOS/Python. Это не приложение, а способ
    // упаковки толкователя, и ровно этот путь был у одного из двух
    // виновников 24 августа. Правило, отсекающее собственного подсудимого,
    // хуже отсутствующего: оно выглядит работающим.
    if (/(\/Applications\/|\/System\/Applications\/|\/Users\/[^/]+\/Applications\/)/.test(к)) return false;

    return /(^|\/|\s)(node|python[\d.]*|Python|npm|npx|bun|deno|ruby|uvicorn|gunicorn)(\s|$)/.test(к);
}

/**
 * Решение по одному процессу. Вынесено отдельной чистой функцией, потому
 * что именно здесь живёт правило «живого родителя не трогаем» — его надо
 * уметь проверить тестом, не запуская ничего в системе.
 */
export function приговор(процесс, { корень, порогМинут }) {
    // родБрошен — корень рода осиротел и является инструментом, а не приложением.
    // выводМёртв — все три дескриптора указывают в ->(none); null = не проверяли.
    const { ppid, pcpu, возраст, команда, родБрошен = false, выводМёртв = null } = процесс;
    if (СИСТЕМНЫЕ.some((п) => команда.startsWith(п))) {
        return { вид: "системный", трогать: false, причина: "служба операционной системы" };
    }
    // Сиротой считается и тот, чей КОРЕНЬ РОДА осиротел: двухуровневый
    // запускатель (next dev → next-server) разводит признаки по разным
    // процессам, и проверка своего ppid по построению промахивается.
    const сирота = ppid === 1 || родБрошен === true;
    const наш = корень ? команда.includes(корень) : true;
    const безДвижения = pcpu < ПОРОГ_ПРОЦЕССОРА;
    const старый = возраст >= порогМинут;

    if (!наш) return { вид: "чужой", трогать: false, причина: "не из этого проекта" };
    if (!сирота) {
        return {
            вид: старый && безДвижения ? "долгий-но-с-родителем" : "живой",
            трогать: false,
            // Тот самый случай: по виду неотличим от зависшего.
            причина: "родитель жив — это чья-то работающая сессия",
        };
    }
    if (!старый) return { вид: "сирота-молодой", трогать: false, причина: "мог только что осиротеть" };
    if (!безДвижения) {
        // ТРЕТИЙ ПРИЗНАК, добавлен 2026-08-24. Крутящийся процесс, чей вывод
        // читать НЕКОМУ, брошен независимо от того, сколько он ест. Все три
        // дескриптора в ->(none) значат, что та сторона канала закрылась
        // вместе с сессией: что бы он ни насчитал, результат не увидит никто.
        //
        // Именно в эту щель провалились оба виновника 24 августа: сервер
        // разработки жёг целое ядро 46 часов, питон три четверти ядра, и оба
        // считались «занятыми делом», потому что процессор был не ноль.
        //
        // Признак осознанно поставлен ВЫШЕ процессора, но НИЖЕ проверки
        // живого родителя: та стоит раньше и остаётся неприкосновенной.
        if (выводМёртв === true) {
            return {
                вид: "завис-крутится",
                трогать: true,
                причина: `сирота ${Math.round(возраст / 60)} ч, жжёт ${pcpu}% процессора, вывод читать некому`,
            };
        }
        // СЛЕПОЕ ПЯТНО, найденное 2026-08-15. Сирота, которая жжёт процессор
        // ОДИННАДЦАТЬ ДНЕЙ, — не «занята делом», а крутится вхолостую. Так
        // нашёлся локальный бэкенд проекта: он отвечал на запросы за 3 мс и
        // при этом накопил 186 часов процессорного времени. Убивать его
        // нельзя (работает и принадлежит владельцу), но и молчать о нём
        // нельзя: из-за него не проходил предпушевой гейт, а причина
        // выглядела как «тесты почему-то не укладываются».
        //
        // Поэтому отдельный вид: НАЗЫВАЕМ, но НЕ ТРОГАЕМ. Решение о
        // перезапуске принимает человек — процесс рабочий.
        const долго = возраст >= ДОЛГО_МИНУТ;
        return {
            вид: долго ? "сирота-жжёт-давно" : "сирота-работает",
            трогать: false,
            причина: долго
                ? `сирота считает ${Math.round(возраст / 60)} ч подряд — похоже на холостой цикл`
                : "считает, значит занят делом",
        };
    }
    return { вид: "завис", трогать: true, причина: `сирота, ${Math.round(возраст)} мин без движения` };
}

/**
 * Мёртв ли вывод: ОБА дескриптора вывода (обычный и ошибки) указывают в
 * `->(none)`, то есть та сторона канала закрыта вместе с породившей сессией.
 *
 * Ввод (дескриптор 0) НЕ проверяется, и это не упущение. Первая версия
 * требовала мёртвыми все три, и живой прогон 2026-08-24 показал, почему так
 * нельзя: у всех трёх найденных брошенных процессов ввод указывал на
 * /dev/null — обычное дело для отвязанного процесса. Правило, требующее
 * мёртвым ещё и ввод, возвращало «жив» на процессах, которые заведомо
 * брошены. Значение имеет только то, читает ли кто-нибудь ВЫВОД.
 *
 * Возвращает true / false / null. NULL — это «не смог проверить», и он
 * НИКОГДА не считается доказательством: при недоступном lsof, отказе в правах
 * или пустом ответе прибор молча ничего не трогает. Ошибаться здесь можно
 * только в сторону бездействия.
 *
 * Стоит один вызов lsof на процесс, поэтому зовётся ТОЛЬКО для кандидатов.
 */
function выводМёртв(pid) {
    try {
        const out = execFileSync("lsof", ["-p", String(pid), "-a", "-d", "1,2", "-Fn"], {
            encoding: "utf8",
            timeout: 4000,
            stdio: ["ignore", "pipe", "ignore"],
        });
        const имена = out.split("\n").filter((с) => с.startsWith("n"));
        if (имена.length === 0) return null; // нечего смотреть — не заключение
        return имена.every((с) => с.includes("(none)"));
    } catch {
        return null; // lsof нет, прав нет, вышло время — молчим
    }
}

function собратьПроцессы() {
    const out = execFileSync("ps", ["-eo", "pid,ppid,etime,pcpu,command"], { encoding: "utf8" });
    const строки = out.split("\n").slice(1).filter(Boolean);
    const список = [];
    for (const с of строки) {
        const m = с.trim().match(/^(\d+)\s+(\d+)\s+(\S+)\s+([\d.]+)\s+(.*)$/);
        if (!m) continue;
        список.push({
            pid: Number(m[1]),
            ppid: Number(m[2]),
            возраст: возрастВМинутах(m[3]),
            pcpu: Number(m[4]),
            команда: m[5],
        });
    }
    return список;
}

