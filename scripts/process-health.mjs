#!/usr/bin/env node
/**
 * process-health — зависшие процессы рабочей машины: найти, назвать, убрать.
 *
 * ЗАЧЕМ. Автономный прогон оставляет за собой хвосты: сессия умирает, а
 * запущенный ею скрипт продолжает висеть. Он не ест процессор и не мешает
 * заметно, поэтому живёт сутками и обнаруживается случайно. Замер
 * 2026-08-15 (projectx-app): фаззер `run-fuzz.mjs` висел 5 часов 24 минуты
 * при собственном потолке выполнения в 200 секунд. Его дескрипторы вывода
 * указывали в никуда — сессия, которая его запустила, умерла, и он ждал
 * события, которое уже не наступит.
 *
 * ГЛАВНОЕ ПРАВИЛО БЕЗОПАСНОСТИ — и оно тут не формальность. Рядом с этим
 * фаззером висели два процесса MCP по 18 часов, и по внешнему виду они
 * ничем не отличались: тот же node, тот же ноль процессора, та же вечность
 * в списке. Разница в одном поле — их РОДИТЕЛЬ ЖИВ, это работающие сессии
 * Claude. Убить такой процесс значит сломать чужую живую работу.
 *
 * Поэтому инструмент трогает только сирот: родитель равен 1 (launchd/init),
 * то есть тот, кто запускал, уже мёртв. Всё остальное он называет, но не
 * трогает — «долго» это не «зависло».
 *
 * ЧТО СЧИТАЕТСЯ ЗАВИСШИМ. Три признака вместе, а не по отдельности:
 *   1. сирота       — родитель 1;
 *   2. наш          — команда указывает на скрипт проекта или на известный
 *                     инструмент прогона (node/python из репозитория);
 *   3. без движения — процессор около нуля дольше порога.
 *
 * Одного признака мало: демон бывает сиротой законно, а долгая сборка
 * законно ест ноль процессора, ожидая ввода-вывода.
 *
 * Использование:
 *   node process-health.mjs                     — только показать
 *   node process-health.mjs --fix               — убрать сирот (сначала TERM, потом KILL)
 *   node process-health.mjs --root <путь>       — что считать «нашим» (умолчание: текущая папка)
 *   node process-health.mjs --minutes 30        — порог возраста, минут (умолчание 30)
 *   node process-health.mjs --json
 *   node process-health.mjs --self-test
 */

import { execFileSync } from "node:child_process";

const ПОРОГ_МИНУТ_ПО_УМОЛЧАНИЮ = 30;
const ПОРОГ_ПРОЦЕССОРА = 1.0; // %
/** Дольше этого «работает» перестаёт быть объяснением. Сутки. */
const ДОЛГО_МИНУТ = 24 * 60;

/** `ps` отдаёт возраст как [[дни-]часы:]минуты:секунды. Переводим в минуты. */
export function возрастВМинутах(строка) {
    if (!строка || typeof строка !== "string") return 0;
    const s = строка.trim();
    let дни = 0;
    let остаток = s;
    const дефис = s.indexOf("-");
    if (дефис > 0) {
        дни = Number(s.slice(0, дефис)) || 0;
        остаток = s.slice(дефис + 1);
    }
    const части = остаток.split(":").map((ч) => Number(ч) || 0);
    let часы = 0;
    let минуты = 0;
    let секунды = 0;
    if (части.length === 3) [часы, минуты, секунды] = части;
    else if (части.length === 2) [минуты, секунды] = части;
    else [секунды] = части;
    return дни * 1440 + часы * 60 + минуты + секунды / 60;
}

/**
 * Решение по одному процессу. Вынесено отдельной чистой функцией, потому
 * что именно здесь живёт правило «живого родителя не трогаем» — его надо
 * уметь проверить тестом, не запуская ничего в системе.
 */
export function приговор(процесс, { корень, порогМинут }) {
    const { ppid, pcpu, возраст, команда } = процесс;
    const сирота = ppid === 1;
    const наш = корень ? команда.includes(корень) : true;
    const безДвижения = pcpu < ПОРОГ_ПРОЦЕССОРА;
    const старый = возраст >= порогМинут;

    if (!наш) return { вид: "чужой", трогать: false, причина: "не из этого проекта" };
    if (!сирота) {
        return {
            вид: старый && безДвижения ? "долгий-но-с-родителем" : "живой",
            трогать: false,
            // Тот самый случай: по виду неотличим от зависшего.
            причина: "родитель жив — это чья-то работающая сессия",
        };
    }
    if (!старый) return { вид: "сирота-молодой", трогать: false, причина: "мог только что осиротеть" };
    if (!безДвижения) {
        // СЛЕПОЕ ПЯТНО, найденное 2026-08-15. Сирота, которая жжёт процессор
        // ОДИННАДЦАТЬ ДНЕЙ, — не «занята делом», а крутится вхолостую. Так
        // нашёлся локальный бэкенд проекта: он отвечал на запросы за 3 мс и
        // при этом накопил 186 часов процессорного времени. Убивать его
        // нельзя (работает и принадлежит владельцу), но и молчать о нём
        // нельзя: из-за него не проходил предпушевой гейт, а причина
        // выглядела как «тесты почему-то не укладываются».
        //
        // Поэтому отдельный вид: НАЗЫВАЕМ, но НЕ ТРОГАЕМ. Решение о
        // перезапуске принимает человек — процесс рабочий.
        const долго = возраст >= ДОЛГО_МИНУТ;
        return {
            вид: долго ? "сирота-жжёт-давно" : "сирота-работает",
            трогать: false,
            причина: долго
                ? `сирота считает ${Math.round(возраст / 60)} ч подряд — похоже на холостой цикл`
                : "считает, значит занят делом",
        };
    }
    return { вид: "завис", трогать: true, причина: `сирота, ${Math.round(возраст)} мин без движения` };
}

function собратьПроцессы() {
    const out = execFileSync("ps", ["-eo", "pid,ppid,etime,pcpu,command"], { encoding: "utf8" });
    const строки = out.split("\n").slice(1).filter(Boolean);
    const список = [];
    for (const с of строки) {
        const m = с.trim().match(/^(\d+)\s+(\d+)\s+(\S+)\s+([\d.]+)\s+(.*)$/);
        if (!m) continue;
        список.push({
            pid: Number(m[1]),
            ppid: Number(m[2]),
            возраст: возрастВМинутах(m[3]),
            pcpu: Number(m[4]),
            команда: m[5],
        });
    }
    return список;
}

function самопроверка() {
    const проверки = [];
    const ок = (имя, условие) => проверки.push({ имя, ок: !!условие });

    ок("возраст: 05:24:39 = 324 мин", Math.round(возрастВМинутах("05:24:39")) === 325);
    ок("возраст: 00:45 = 0.75 мин", Math.abs(возрастВМинутах("00:45") - 0.75) < 0.01);
    ок("возраст: 1-07:43:26 = сутки с лишним", возрастВМинутах("1-07:43:26") > 1900);
    ок("возраст: мусор = 0", возрастВМинутах(null) === 0);

    const общее = { корень: "/repo", порогМинут: 30 };
    ок(
        "сирота без движения — трогаем",
        приговор({ ppid: 1, pcpu: 0, возраст: 300, команда: "node /repo/x.mjs" }, общее).трогать === true,
    );
    ок(
        "ЖИВОЙ РОДИТЕЛЬ — не трогаем, даже если висит 18 часов",
        приговор({ ppid: 4242, pcpu: 0, возраст: 1080, команда: "node /repo/x.mjs" }, общее).трогать === false,
    );
    ок(
        "сирота, но считает — не трогаем",
        приговор({ ppid: 1, pcpu: 42, возраст: 300, команда: "node /repo/x.mjs" }, общее).трогать === false,
    );
    ок(
        "сирота, но молодой — не трогаем",
        приговор({ ppid: 1, pcpu: 0, возраст: 3, команда: "node /repo/x.mjs" }, общее).трогать === false,
    );
    ок(
        "чужой процесс — не трогаем",
        приговор({ ppid: 1, pcpu: 0, возраст: 300, команда: "node /other/x.mjs" }, общее).трогать === false,
    );
    ок(
        "сирота, жгущая процессор ОДИННАДЦАТЬ ДНЕЙ — называется холостым циклом",
        приговор({ ppid: 1, pcpu: 73, возраст: 16800, команда: "python /repo/run.py" }, общее).вид ===
            "сирота-жжёт-давно",
    );
    ок(
        "но её НЕ трогаем: работает и принадлежит человеку",
        приговор({ ppid: 1, pcpu: 73, возраст: 16800, команда: "python /repo/run.py" }, общее).трогать === false,
    );
    ок(
        "сирота, жгущая два часа — ещё просто занята делом",
        приговор({ ppid: 1, pcpu: 73, возраст: 120, команда: "python /repo/run.py" }, общее).вид ===
            "сирота-работает",
    );
    ок(
        "без корня считаем нашим всё",
        приговор({ ppid: 1, pcpu: 0, возраст: 300, команда: "node /any/x.mjs" }, { корень: null, порогМинут: 30 })
            .трогать === true,
    );

    const плохо = проверки.filter((п) => !п.ок);
    for (const п of проверки) console.log(`  ${п.ок ? "✓" : "✗"} ${п.имя}`);
    console.log(плохо.length ? `\n✗ провалено ${плохо.length} из ${проверки.length}` : `\n✓ все ${проверки.length}`);
    process.exit(плохо.length ? 1 : 0);
}

function main() {
    const args = process.argv.slice(2);
    if (args.includes("--self-test")) return самопроверка();

    const чинить = args.includes("--fix");
    const какJson = args.includes("--json");
    const iКорень = args.indexOf("--root");
    const корень = iКорень >= 0 ? args[iКорень + 1] : process.cwd();
    const iМин = args.indexOf("--minutes");
    const порогМинут = iМин >= 0 ? Number(args[iМин + 1]) : ПОРОГ_МИНУТ_ПО_УМОЛЧАНИЮ;

    const процессы = собратьПроцессы();
    const свои = процессы.filter((п) => п.команда.includes(корень) && п.pid !== process.pid);

    const зависшие = [];
    const подозрительные = [];
    const жгут = [];
    for (const п of свои) {
        const в = приговор(п, { корень, порогМинут });
        if (в.трогать) зависшие.push({ ...п, ...в });
        else if (в.вид === "долгий-но-с-родителем") подозрительные.push({ ...п, ...в });
        else if (в.вид === "сирота-жжёт-давно") жгут.push({ ...п, ...в });
    }

    // ХОЛОСТЫЕ ЦИКЛЫ ИЩЕМ ПО ВСЕЙ МАШИНЕ, а не только в папке проекта.
    // Именно на этом сторож промахнулся: процесс жёг 73% процессора
    // одиннадцать дней, но его команда не содержала пути проекта, и он не
    // попадал в выборку вовсе. Загрузка машины — вещь общая: чужой холостой
    // цикл ломает наш предпушевой гейт ровно так же, как свой.
    for (const п of процессы) {
        if (п.pid === process.pid) continue;
        if (свои.includes(п)) continue;
        if (п.ppid !== 1) continue;
        if (п.pcpu < 20) continue;
        if (п.возраст < ДОЛГО_МИНУТ) continue;
        жгут.push({ ...п, вид: "сирота-жжёт-давно", трогать: false, чужой: true,
            причина: `сирота считает ${Math.round(п.возраст / 60)} ч подряд, ${п.pcpu}% процессора` });
    }

    const убрано = [];
    if (чинить) {
        for (const з of зависшие) {
            try {
                process.kill(з.pid, "SIGTERM");
                const до = Date.now();
                while (Date.now() - до < 2000) {
                    try { process.kill(з.pid, 0); } catch { break; }
                }
                try { process.kill(з.pid, 0); process.kill(з.pid, "SIGKILL"); } catch { /* уже умер */ }
                убрано.push(з.pid);
            } catch (e) {
                з.ошибка = String(e && e.message ? e.message : e);
            }
        }
    }

    if (какJson) {
        console.log(JSON.stringify({ корень, порогМинут, зависшие, подозрительные, жгут, убрано }, null, 2));
        return;
    }

    if (!зависшие.length && !подозрительные.length && !жгут.length) {
        console.log(`[процессы] зависших нет (смотрел процессы из ${корень}, порог ${порогМинут} мин)`);
        return;
    }
    if (зависшие.length) {
        console.log(`[процессы] ЗАВИСШИЕ: ${зависшие.length}${чинить ? ` — убрано ${убрано.length}` : ""}`);
        for (const з of зависшие) {
            console.log(`   ${з.pid}  ${з.причина}`);
            console.log(`         ${з.команда.slice(0, 100)}`);
        }
        if (!чинить) console.log("   → убрать: тот же вызов с --fix");
    }
    if (жгут.length) {
        console.log(`[процессы] ХОЛОСТОЙ ЦИКЛ — называю, но НЕ трогаю (работают): ${жгут.length}`);
        for (const ж of жгут) {
            console.log(`   ${ж.pid}  ${ж.причина}`);
            console.log(`         ${ж.команда.slice(0, 100)}`);
        }
        console.log("   → это решение человека: процесс рабочий, но ест машину");
    }
    if (подозрительные.length) {
        console.log(`[процессы] долгие, но с ЖИВЫМ родителем — не трогаю: ${подозрительные.length}`);
        for (const п of подозрительные) console.log(`   ${п.pid}  ${Math.round(п.возраст)} мин  ${п.команда.slice(0, 80)}`);
    }
}

main();
